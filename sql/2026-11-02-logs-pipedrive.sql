create table if not exists dash2.logs_pipedrive (
  id bigint generated by default as identity primary key,
  criado_em timestamp default now(),
  atualizado_em timestamp,
  chave text not null unique,
  ocorrencias integer not null default 1,
  data date not null,
  hora time,
  usuario_acao text,
  id_user bigint references dash2.users(id),
  atividade text not null,
  acao_evento text,
  cliente_nome text,
  telefone text,
  telefone_digitos text,
  quem_indicou text,
  prospectado_por text,
  linkedin text,
  instagram text,
  url_negocio text
);

grant select, insert, update, delete on dash2.logs_pipedrive to service_role;
grant usage, select on all sequences in schema dash2 to service_role;

notify pgrst, 'reload schema';
