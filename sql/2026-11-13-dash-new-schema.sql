-- Schema dash_new: dados das planilhas de funil (Sellers, SDRs, Closers, Financeiro,
-- Logs Pipedrive e Contas de LinkedIn/Instagram). Segue o modelo de dash2
-- (sql/2026-10-26-dash2-schema.sql), sem a tabela de Dripify: os funis de
-- LinkedIn e Instagram entram em contas_funil / metricas_contas.
--
-- As tabelas de métricas guardam uma linha por pessoa e dia (unique (id_user, data))
-- e a view dash_new.vw_metricas gera o formato longo que o dashboard consome.
--
-- Lição de sql/2026-09-19-grant-user-metas.sql: sem GRANT pro service_role a
-- tabela some em silêncio (o BFF degrada erro de consulta pra lista vazia).
-- Por isso o script termina com os GRANTs e o reload do PostgREST.
--
-- Idempotente: pode rodar de novo sem efeito colateral.
-- Rodar: .venv/bin/python -m scripts.rodar_sql sql/2026-11-13-dash-new-schema.sql

create schema if not exists dash_new;

create table if not exists dash_new.cargos (cargo text primary key);
insert into dash_new.cargos (cargo) values ('seller'), ('sdr'), ('closer') on conflict do nothing;

create table if not exists dash_new.users (
  id bigint generated by default as identity primary key,
  nome text not null,
  email text unique,
  imagem_url text,
  active boolean not null default true,
  role text not null default 'member',
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists dash_new.user_cargos (
  id_user bigint not null references dash_new.users(id) on delete cascade,
  cargo text not null references dash_new.cargos(cargo),
  criado_em timestamptz not null default now(),
  primary key (id_user, cargo)
);

create table if not exists dash_new.metas (
  id bigint generated by default as identity primary key,
  id_user bigint not null,
  cargo text not null,
  metrica text not null,
  valor_diario integer not null check (valor_diario >= 0),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, cargo, metrica),
  foreign key (id_user, cargo) references dash_new.user_cargos(id_user, cargo) on delete cascade
);

create table if not exists dash_new.metricas_sellers (
  id bigint generated by default as identity primary key,
  id_user bigint not null references dash_new.users(id),
  data date not null,
  key_data_ref_user text not null unique,
  fups integer,
  numeros_captados integer,
  indicacoes integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, data)
);

create table if not exists dash_new.metricas_sdrs (
  id bigint generated by default as identity primary key,
  id_user bigint not null references dash_new.users(id),
  data date not null,
  key_data_ref_user text not null unique,
  ligacoes_efetuadas integer,
  ligacoes_realizadas integer,
  inscricoes_realizadas integer,
  indicacoes integer,
  reunioes_agendadas integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, data)
);

create table if not exists dash_new.metricas_closers (
  id bigint generated by default as identity primary key,
  id_user bigint not null references dash_new.users(id),
  data date not null,
  key_data_ref_user text not null unique,
  ligacoes_agendadas integer,
  ligacoes_realizadas integer,
  reunioes_agendadas integer,
  reunioes_realizadas integer,
  indicacoes integer,
  inscricoes_realizadas integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, data)
);

create table if not exists dash_new.cliente_faturamento (
  id bigint generated by default as identity primary key,
  criado_em timestamp default now(),
  atualizado_em timestamp,
  nome text,
  telefone bigint unique
);

create table if not exists dash_new.metricas_faturamento (
  id bigint generated by default as identity primary key,
  criado_em timestamp default now(),
  atualizado_em timestamp,
  user_sdr bigint references dash_new.users(id),
  user_closer bigint references dash_new.users(id),
  metodo_pagamento text,
  produto text,
  canal text,
  data_venda timestamp,
  valor_bruto_contrato double precision,
  valor_entrada double precision,
  condicao_pagamento text,
  num_parcelas integer,
  imposto double precision,
  taxa double precision,
  liquido_entrada double precision,
  id_cliente bigint references dash_new.cliente_faturamento(id),
  key_id_cliente_data_venda text unique,
  taxa_pgto_2 double precision,
  liquido_pgto_2 double precision,
  valor_pgto_2 double precision,
  forma_pgto_2 text,
  id_planilha integer unique,
  num_parcelas_pgto_2 integer,
  observacoes text
);

create table if not exists dash_new.recebimentos_faturamento (
  id bigint generated by default as identity primary key,
  criado_em timestamp default now(),
  atualizado_em timestamp,
  id_planilha_venda integer not null references dash_new.metricas_faturamento(id_planilha) on delete cascade,
  mes date not null,
  pago double precision,
  liquido double precision,
  unique (id_planilha_venda, mes)
);

create table if not exists dash_new.logs_pipedrive (
  id bigint generated by default as identity primary key,
  criado_em timestamp default now(),
  atualizado_em timestamp,
  chave text not null unique,
  ocorrencias integer not null default 1,
  data date not null,
  hora time,
  usuario_acao text,
  id_user bigint references dash_new.users(id),
  atividade text not null,
  acao_evento text,
  cliente_nome text,
  telefone text,
  telefone_digitos text,
  quem_indicou text,
  prospectado_por text,
  linkedin text,
  instagram text,
  url_negocio text
);

create table if not exists dash_new.contas_funil (
  id bigint generated by default as identity primary key,
  canal text not null check (canal in ('linkedin', 'instagram')),
  nome text not null,
  id_seller bigint references dash_new.users(id),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (canal, nome)
);

create table if not exists dash_new.metricas_contas (
  id bigint generated by default as identity primary key,
  id_conta bigint not null references dash_new.contas_funil(id) on delete cascade,
  data date not null,
  conexoes_enviadas integer,
  conexoes_aceitas integer,
  mensagens_abordagem integer,
  abordagens integer,
  follows_abordagem integer,
  respondidos integer,
  in_mails integer,
  fups integer,
  numeros_captados integer,
  indicacoes integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_conta, data)
);

create or replace view dash_new.vw_metricas as
select m.data, m.id_user, u.nome, 'seller'::text as cargo, null::text as conta, v.metrica, v.valor
  from dash_new.metricas_sellers m
  join dash_new.users u on u.id = m.id_user
 cross join lateral (values
        ('fups', m.fups), ('numeros_captados', m.numeros_captados), ('indicacoes', m.indicacoes)
      ) as v(metrica, valor)
 where v.valor is not null
union all
select m.data, m.id_user, u.nome, 'sdr'::text, null::text, v.metrica, v.valor
  from dash_new.metricas_sdrs m
  join dash_new.users u on u.id = m.id_user
 cross join lateral (values
        ('ligacoes_efetuadas', m.ligacoes_efetuadas), ('ligacoes_realizadas', m.ligacoes_realizadas),
        ('inscricoes_realizadas', m.inscricoes_realizadas), ('indicacoes', m.indicacoes),
        ('reunioes_agendadas', m.reunioes_agendadas)
      ) as v(metrica, valor)
 where v.valor is not null
union all
select m.data, m.id_user, u.nome, 'closer'::text, null::text, v.metrica, v.valor
  from dash_new.metricas_closers m
  join dash_new.users u on u.id = m.id_user
 cross join lateral (values
        ('ligacoes_agendadas', m.ligacoes_agendadas), ('ligacoes_realizadas', m.ligacoes_realizadas),
        ('reunioes_agendadas', m.reunioes_agendadas), ('reunioes_realizadas', m.reunioes_realizadas),
        ('indicacoes', m.indicacoes), ('inscricoes_realizadas', m.inscricoes_realizadas)
      ) as v(metrica, valor)
 where v.valor is not null;

grant usage on schema dash_new to service_role;
grant select, insert, update, delete on all tables in schema dash_new to service_role;
grant usage, select on all sequences in schema dash_new to service_role;
alter default privileges in schema dash_new grant select, insert, update, delete on tables to service_role;

notify pgrst, 'reload schema';
