create table if not exists dash2.metricas_faturamento_bkp_20261028 as table dash2.metricas_faturamento;

alter table dash2.metricas_faturamento
  add column if not exists id_planilha integer,
  add column if not exists num_parcelas_pgto_2 integer,
  add column if not exists observacoes text;
do $$ begin alter table dash2.metricas_faturamento add constraint metricas_faturamento_id_planilha_key unique (id_planilha); exception when duplicate_table or duplicate_object then null; end $$;

create table if not exists dash2.recebimentos_faturamento (
  id bigint generated by default as identity primary key,
  criado_em timestamp default now(),
  atualizado_em timestamp,
  id_planilha_venda integer not null references dash2.metricas_faturamento(id_planilha) on delete cascade,
  mes date not null,
  pago double precision,
  liquido double precision,
  unique (id_planilha_venda, mes)
);

grant select, insert, update, delete on dash2.metricas_faturamento, dash2.cliente_faturamento, dash2.recebimentos_faturamento to service_role;
