-- Página Funil SDR (planilha PLANILHA_SDRS_ID).
--
-- metricas_funil_sdr: uma linha por SDR e dia, espelho das abas por pessoa
--   (Juca, Jennifer). A aba SDR3 não tem user e é ignorada pelo worker.
-- metas_funil_sdr: metas da aba "Dashboard SDR":
--   periodo 'dia'    -> meta diária de cada SDR (id_user preenchido);
--   periodo 'semana' -> "Meta Semanal [Editar]" do time (id_user null);
--   periodo 'mes'    -> "Meta Mensal [Editar]" do time (id_user null).
--
-- Cadastra a Jennifer como user com cargo sdr. O id 4 virou "Duda" (seller)
-- no dash_new, e sem user a aba Jennifer era pulada em silêncio.
--
-- Idempotente. Rodar: .venv/bin/python -m scripts.rodar_sql sql/2026-11-16-funil-sdr.sql

create table if not exists dash_new.metricas_funil_sdr (
  id bigint generated by default as identity primary key,
  id_user bigint not null references dash_new.users(id) on delete cascade,
  data date not null,
  ligacoes_efetuadas integer,
  ligacoes_realizadas integer,
  inscricoes_realizadas integer,
  indicacoes integer,
  reunioes_agendadas integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, data)
);

create table if not exists dash_new.metas_funil_sdr (
  id bigint generated by default as identity primary key,
  metrica text not null,
  periodo text not null check (periodo in ('dia', 'semana', 'mes')),
  id_user bigint references dash_new.users(id) on delete cascade,
  valor integer not null check (valor >= 0),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  check ((periodo = 'dia') = (id_user is not null)),
  unique nulls not distinct (metrica, periodo, id_user)
);

insert into dash_new.users (nome, active)
select 'Jennifer', true
 where not exists (select 1 from dash_new.users where nome = 'Jennifer');

insert into dash_new.user_cargos (id_user, cargo)
select id, 'sdr' from dash_new.users where nome = 'Jennifer'
on conflict do nothing;

grant select, insert, update, delete on dash_new.metricas_funil_sdr, dash_new.metas_funil_sdr to service_role;
grant usage, select on all sequences in schema dash_new to service_role;

notify pgrst, 'reload schema';
