-- Schema novo dash2 (substitui o schema dash nas planilhas).
--
-- Os dados vêm das planilhas Sellers, SDRs, Closers e Dripify. As tabelas de
-- métricas guardam uma linha por pessoa e dia (unique (id_user, data)) e a
-- view dash2.vw_metricas gera o formato longo que o dashboard consome.
--
-- Lição de sql/2026-09-19-grant-user-metas.sql: sem GRANT pro service_role a
-- tabela some em silêncio (o BFF degrada erro de consulta pra lista vazia).
-- Por isso o script termina com os GRANTs e o reload do PostgREST.

create schema if not exists dash2;

create table if not exists dash2.cargos (cargo text primary key);
insert into dash2.cargos (cargo) values ('seller'), ('sdr'), ('closer'), ('dripify') on conflict do nothing;

create table if not exists dash2.users (
  id bigint generated by default as identity primary key,
  nome text not null,
  email text unique,
  imagem_url text,
  active boolean not null default true,
  role text not null default 'member',
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists dash2.user_cargos (
  id_user bigint not null references dash2.users(id) on delete cascade,
  cargo text not null references dash2.cargos(cargo),
  criado_em timestamptz not null default now(),
  primary key (id_user, cargo)
);

create table if not exists dash2.metas (
  id bigint generated by default as identity primary key,
  id_user bigint not null,
  cargo text not null,
  metrica text not null,
  valor_diario integer not null check (valor_diario >= 0),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, cargo, metrica),
  foreign key (id_user, cargo) references dash2.user_cargos(id_user, cargo) on delete cascade
);

create table if not exists dash2.metricas_sellers (
  id bigint generated by default as identity primary key,
  id_user bigint not null references dash2.users(id),
  data date not null,
  key_data_ref_user text not null unique,
  fups integer,
  numeros_captados integer,
  indicacoes integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, data)
);

create table if not exists dash2.metricas_sdrs (
  id bigint generated by default as identity primary key,
  id_user bigint not null references dash2.users(id),
  data date not null,
  key_data_ref_user text not null unique,
  ligacoes_efetuadas integer,
  ligacoes_realizadas integer,
  inscricoes_realizadas integer,
  indicacoes integer,
  reunioes_agendadas integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, data)
);

create table if not exists dash2.metricas_closers (
  id bigint generated by default as identity primary key,
  id_user bigint not null references dash2.users(id),
  data date not null,
  key_data_ref_user text not null unique,
  ligacoes_agendadas integer,
  ligacoes_realizadas integer,
  reunioes_agendadas integer,
  reunioes_realizadas integer,
  indicacoes integer,
  inscricoes_realizadas integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, data)
);

create table if not exists dash2.metricas_dripify (
  id bigint generated by default as identity primary key,
  id_user bigint not null references dash2.users(id),
  data date not null,
  key_data_ref_user text not null unique,
  conexoes_enviadas integer,
  conexoes_aceitas integer,
  abordagens integer,
  in_mails integer,
  fups integer,
  numeros_captados integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (id_user, data)
);

create table if not exists dash2.cliente_faturamento (
  id bigint generated by default as identity primary key,
  criado_em timestamp default now(),
  atualizado_em timestamp,
  nome text,
  telefone bigint
);

create table if not exists dash2.metricas_faturamento (
  id bigint generated by default as identity primary key,
  criado_em timestamp default now(),
  atualizado_em timestamp,
  user_sdr bigint references dash2.users(id),
  user_closer bigint references dash2.users(id),
  metodo_pagamento text,
  produto text,
  canal text,
  data_venda timestamp,
  valor_bruto_contrato double precision,
  valor_entrada double precision,
  condicao_pagamento text,
  num_parcelas integer,
  imposto double precision,
  taxa double precision,
  liquido_entrada double precision,
  id_cliente bigint references dash2.cliente_faturamento(id),
  key_id_cliente_data_venda text,
  taxa_pgto_2 double precision,
  liquido_pgto_2 double precision,
  valor_pgto_2 double precision,
  forma_pgto_2 text
);

create table if not exists dash2.sync_log (
  id bigint generated by default as identity primary key,
  rodou_em timestamp default now(),
  linhas integer,
  status text,
  erro text
);

-- Constraints UNIQUE que existem em dash (pegas no pg_constraint), replicadas
-- aqui pra o schema novo ficar com a mesma garantia. Idempotente.
do $$ begin alter table dash2.metricas_faturamento add constraint metricas_faturamento_key_id_cliente_data_venda_key UNIQUE (key_id_cliente_data_venda); exception when duplicate_table or duplicate_object then null; end $$;
do $$ begin alter table dash2.cliente_faturamento add constraint cliente_faturamento_telefone_key UNIQUE (telefone); exception when duplicate_table or duplicate_object then null; end $$;

create or replace view dash2.vw_metricas as
select m.data, m.id_user, u.nome, 'seller'::text as cargo, null::text as conta, v.metrica, v.valor
  from dash2.metricas_sellers m
  join dash2.users u on u.id = m.id_user
 cross join lateral (values
        ('fups', m.fups), ('numeros_captados', m.numeros_captados), ('indicacoes', m.indicacoes)
      ) as v(metrica, valor)
 where v.valor is not null
union all
select m.data, m.id_user, u.nome, 'sdr'::text, null::text, v.metrica, v.valor
  from dash2.metricas_sdrs m
  join dash2.users u on u.id = m.id_user
 cross join lateral (values
        ('ligacoes_efetuadas', m.ligacoes_efetuadas), ('ligacoes_realizadas', m.ligacoes_realizadas),
        ('inscricoes_realizadas', m.inscricoes_realizadas), ('indicacoes', m.indicacoes),
        ('reunioes_agendadas', m.reunioes_agendadas)
      ) as v(metrica, valor)
 where v.valor is not null
union all
select m.data, m.id_user, u.nome, 'closer'::text, null::text, v.metrica, v.valor
  from dash2.metricas_closers m
  join dash2.users u on u.id = m.id_user
 cross join lateral (values
        ('ligacoes_agendadas', m.ligacoes_agendadas), ('ligacoes_realizadas', m.ligacoes_realizadas),
        ('reunioes_agendadas', m.reunioes_agendadas), ('reunioes_realizadas', m.reunioes_realizadas),
        ('indicacoes', m.indicacoes), ('inscricoes_realizadas', m.inscricoes_realizadas)
      ) as v(metrica, valor)
 where v.valor is not null
union all
select m.data, m.id_user, u.nome, 'dripify'::text, null::text, v.metrica, v.valor
  from dash2.metricas_dripify m
  join dash2.users u on u.id = m.id_user
 cross join lateral (values
        ('conexoes_enviadas', m.conexoes_enviadas), ('conexoes_aceitas', m.conexoes_aceitas),
        ('abordagens', m.abordagens), ('in_mails', m.in_mails),
        ('fups', m.fups), ('numeros_captados', m.numeros_captados)
      ) as v(metrica, valor)
 where v.valor is not null;

grant usage on schema dash2 to service_role;
grant select on all tables in schema dash2 to service_role;
alter default privileges in schema dash2 grant select on tables to service_role;

notify pgrst, 'reload schema';
